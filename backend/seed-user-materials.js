async function main() {
    console.log("Clearing existing Material table...");
    await prisma.material.deleteMany();

    console.log("Seeding materials...");
    let count = 0;
    for (const name of materialsList) {
        let category = "Ortho"; // Default
        const nameUpper = name.toUpperCase();
        if (nameUpper.includes("ZIRCON") || nameUpper.includes("ZR")) {
            category = "Zircon";
        } else if (nameUpper.includes("CERAMIC") || nameUpper.includes("ENAMEL") || nameUpper.includes("OPAQUE") || nameUpper.includes("GLAZE") || nameUpper.includes("DENTIN") || nameUpper.includes("FIRING") || nameUpper.includes("EMAX") || nameUpper.includes("IPS") || nameUpper.includes("VITA")) {
            category = "Ceramic";
        } else if (nameUpper.includes("METAL") || nameUpper.includes("CASTING") || nameUpper.includes("ALLOY") || nameUpper.includes("CRUCIBLE") || nameUpper.includes("CALIPER") || nameUpper.includes("CLASP") || nameUpper.includes("WIRE") || nameUpper.includes("SPRUE") || nameUpper.includes("SOLDER")) {
            category = "Metal";
        } else if (nameUpper.includes("RESIN") || nameUpper.includes("FILM") || nameUpper.includes("PRINTER") || nameUpper.includes("SCREEN") || nameUpper.includes("BIO ART") || nameUpper.includes("NNT") || nameUpper.includes("OTRES") || nameUpper.includes("VERACRIL") || nameUpper.includes("TRIPLEX") || nameUpper.includes("MONOMER") || nameUpper.includes("POLYMER") || nameUpper.includes("REZPRO")) {
            category = "Resins";
        } else if (nameUpper.includes("ORTHO") || nameUpper.includes("BAND") || nameUpper.includes("SCREW") || nameUpper.includes("RETAINER") || nameUpper.includes("HAWLEY") || nameUpper.includes("TONGUE") || nameUpper.includes("TWIN BLOCK") || nameUpper.includes("APPLIANCE") || nameUpper.includes("BITE") || nameUpper.includes("HABIT") || nameUpper.includes("COIL") || nameUpper.includes("NITI")) {
            category = "Ortho";
        }

        await prisma.material.create({
            data: {
                name: name,
                category: category,
                stock: Math.floor(Math.random() * 30) + 10,
                unit: "pc",
                minStock: 5
            }
        });
        count++;
    }
    console.log(`Successfully seeded ${count} materials!`);
}

main().catch(console.error).finally(() => prisma.$disconnect());
